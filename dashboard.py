import json
from pathlib import Path

import pandas as pd
import streamlit as st

st.set_page_config(
    page_title="Cowrie Threat Detection Lab",
    page_icon="🛡️",
    layout="wide",
)

st.title("🛡️ Cowrie Threat Detection Dashboard")
st.caption("AWS SSH Honeypot | Detection Engineering Lab")

LOG_DIR = Path("data/cowrie/logs")
from detections.detect_user_discovery import TEST_IPS
OWN_IPS = set(TEST_IPS)

events = []

for file in sorted(LOG_DIR.glob("cowrie.json*")):
    if not file.is_file():
        continue

    with file.open(encoding="utf-8") as handle:
        for line in handle:
            try:
                event = json.loads(line)
                if isinstance(event, dict):
                    events.append(event)
            except json.JSONDecodeError:
                continue

if not events:
    st.error("No Cowrie security events found.")
    st.stop()

df = pd.DataFrame(events)
df["timestamp"] = pd.to_datetime(
    df["timestamp"], utc=True, errors="coerce"
)
df["src_ip"] = df["src_ip"].fillna("Unknown")
df["eventid"] = df["eventid"].fillna("Unknown")

st.sidebar.header("Filters")

exclude_tests = st.sidebar.checkbox(
    "Exclude my test traffic", value=False
)

if exclude_tests:
    df = df[~df["src_ip"].isin(OWN_IPS)]

connections = df[df["eventid"] == "cowrie.session.connect"]
logins = df[df["eventid"].str.startswith("cowrie.login.")]
commands = df[df["eventid"] == "cowrie.command.input"]

c1, c2, c3, c4 = st.columns(4)

c1.metric("Total Events", len(df))
c2.metric("SSH Connections", len(connections))
c3.metric("Login Attempts", len(logins))
c4.metric("Commands Captured", len(commands))

st.divider()

st.subheader("SSH Activity Over Time")

timeline = (
    df.dropna(subset=["timestamp"])
    .set_index("timestamp")
    .resample("h")
    .size()
)

st.line_chart(timeline)

left, right = st.columns(2)

with left:
    st.subheader("Top Source IPs")
    st.bar_chart(
        df[df["src_ip"] != "Unknown"]["src_ip"]
        .value_counts()
        .head(10)
    )

with right:
    st.subheader("Event Categories")
    st.bar_chart(df["eventid"].value_counts().head(10))

st.subheader("Captured Commands")

if not commands.empty:
    st.dataframe(
        commands.reindex(
            columns=["timestamp", "src_ip", "input"]
        ),
        use_container_width=True,
        hide_index=True,
    )
else:
    st.info("No commands recorded for the selected traffic.")

st.subheader("Recent Security Events")

st.dataframe(
    df.sort_values("timestamp", ascending=False)
    .reindex(
        columns=[
            "timestamp",
            "src_ip",
            "eventid",
            "session",
            "username",
            "password",
        ]
    ),
    use_container_width=True,
    hide_index=True,
)

st.caption("Local analysis only. No dashboard ports are exposed on AWS.")


# Reuse the tested detection engine
from detections.detect_user_discovery import detect

st.divider()
st.subheader("Detection Alerts")
st.caption("Alerts generated by our tested Python detection engine")

alerts = detect(events)

if alerts:
    st.warning(f"{len(alerts)} detection alert(s) identified")

    alert_data = pd.DataFrame([
        {
            "Timestamp": alert["timestamp"],
            "Severity": alert["severity"].title(),
            "Detection": alert["rule"],
            "Source IP": alert["source_ip"],
            "Session": alert["session"],
            "Command": alert["command"],
            "MITRE ATT&CK": alert["mitre"],
        }
        for alert in alerts
    ])

    st.dataframe(
        alert_data,
        use_container_width=True,
        hide_index=True,
    )
else:
    st.success("No user-discovery alerts detected.")

# Detection Rule 002: Repeated SSH authentication failures
from detections.detect_bruteforce import detect as detect_bruteforce

st.divider()
st.subheader("SSH Brute-Force Detection")
st.caption("Rule 002 | Five failed login attempts within five minutes")

bruteforce_alerts = detect_bruteforce(events)

if bruteforce_alerts:
    st.error(
        f"{len(bruteforce_alerts)} potential brute-force alert(s) detected"
    )

    brute_df = pd.DataFrame([
        {
            "Timestamp": alert["timestamp"],
            "Severity": alert["severity"].title(),
            "Source IP": alert["source_ip"],
            "Failed Attempts": alert["failed_attempts"],
            "Window (minutes)": alert["window_minutes"],
            "MITRE ATT&CK": alert["mitre"],
        }
        for alert in bruteforce_alerts
    ])

    st.dataframe(
        brute_df,
        use_container_width=True,
        hide_index=True,
    )
else:
    st.info(
        "No sources met the brute-force detection threshold "
        "in the current evidence snapshot."
    )
